//! SPA page routes and redirects.
//!
//! The routes file is plain text, one entry per line, `#` starts a comment:
//!
//! ```text
//! page /agents          # exact path gets the HTML shell
//! page /md/$name        # `$x` matches exactly one non-empty segment
//! redirect / /console   # 302 Location: /console (query kept)
//! ```
//!
//! `galion-console-static gen-routes` generates it from `routeTree.gen.ts` of the
//! console tree, so it tracks the TanStack route tree. A path that is not a
//! page, not a redirect, not a built file and not proxied is 404.

use std::fmt;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Redirect {
    pub from: String,
    pub to: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Routes {
    pages: Vec<Vec<String>>,
    redirects: Vec<Redirect>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParseError {
    pub line: usize,
    pub msg: String,
}

impl fmt::Display for ParseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "routes line {}: {}", self.line, self.msg)
    }
}

impl std::error::Error for ParseError {}

fn valid_route_path(p: &str) -> bool {
    p.starts_with('/') && crate::path::sanitize(p).is_ok() && (p == "/" || !p.ends_with('/'))
}

fn segments(p: &str) -> Vec<String> {
    p.split('/')
        .filter(|s| !s.is_empty())
        .map(str::to_string)
        .collect()
}

impl Routes {
    /// Parse the routes file text.
    pub fn parse(text: &str) -> Result<Routes, ParseError> {
        let mut r = Routes::default();
        for (i, raw) in text.lines().enumerate() {
            let line = raw.split('#').next().unwrap_or("").trim();
            if line.is_empty() {
                continue;
            }
            let err = |msg: &str| ParseError {
                line: i + 1,
                msg: msg.to_string(),
            };
            let parts: Vec<&str> = line.split_whitespace().collect();
            match parts.as_slice() {
                ["page", p] => {
                    if !valid_route_path(p) {
                        return Err(err("bad page path"));
                    }
                    if p.split('/').any(|s| s.starts_with('$') && s.len() == 1) {
                        return Err(err("splat `$` is not supported; name the segment"));
                    }
                    r.pages.push(segments(p));
                }
                ["redirect", from, to] => {
                    if !valid_route_path(from) || from.contains('$') {
                        return Err(err("bad redirect source"));
                    }
                    if !valid_route_path(to) || to.contains('$') {
                        return Err(err("redirect target must be a local path"));
                    }
                    r.redirects.push(Redirect {
                        from: from.to_string(),
                        to: to.to_string(),
                    });
                }
                _ => return Err(err("expected `page <path>` or `redirect <from> <to>`")),
            }
        }
        Ok(r)
    }

    /// Number of page patterns.
    pub fn page_count(&self) -> usize {
        self.pages.len()
    }

    /// Redirect target for an exact sanitized path.
    pub fn redirect(&self, path: &str) -> Option<&str> {
        self.redirects
            .iter()
            .find(|r| r.from == path)
            .map(|r| r.to.as_str())
    }

    /// True when a sanitized path is an SPA page that gets the HTML shell.
    pub fn is_page(&self, path: &str) -> bool {
        if path != "/" && path.ends_with('/') {
            return false;
        }
        let segs: Vec<&str> = path.split('/').filter(|s| !s.is_empty()).collect();
        self.pages.iter().any(|pat| {
            pat.len() == segs.len()
                && pat
                    .iter()
                    .zip(&segs)
                    .all(|(p, s)| (p.starts_with('$') && !s.is_empty()) || p == s)
        })
    }
}

/// Build a routes file from a TanStack `routeTree.gen.ts`: the `fullPaths:` union
/// minus server routes under `/api/` and splat routes (`.../$`). Pure Rust
/// replacement for the former awk step; no JS tooling involved.
pub fn from_route_tree(text: &str, redirects: &[(String, String)]) -> Result<String, ParseError> {
    let mut out =
        String::from("# generated by `galion-console-static gen-routes` from routeTree.gen.ts\n");
    let mut in_block = false;
    let mut n = 0;
    for line in text.lines() {
        let t = line.trim();
        if !in_block {
            in_block = t == "fullPaths:";
            continue;
        }
        let Some(p) = t.strip_prefix("| ") else { break };
        let p = p.trim_matches(|c| c == '\'' || c == '"');
        if !p.starts_with('/') || p.starts_with("/api/") || p.ends_with("/$") {
            continue;
        }
        out.push_str(&format!("page {p}\n"));
        n += 1;
    }
    if n == 0 {
        return Err(ParseError {
            line: 0,
            msg: "no fullPaths page routes found".into(),
        });
    }
    for (f, t) in redirects {
        out.push_str(&format!("redirect {f} {t}\n"));
    }
    Routes::parse(&out)?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn route_tree_import() {
        let tree = "export interface FileRoutesByFullPath {}\n  fullPaths:\n    | '/'\n    | '/agents'\n    | '/md/$name'\n    | '/api/v1/health'\n    | '/api/v1/analytics/$'\n  fileRoutesByTo: FileRoutesByTo\n  to:\n    | '/x'\n";
        let out = from_route_tree(tree, &[("/".into(), "/console".into())]).unwrap();
        let r = Routes::parse(&out).unwrap();
        assert_eq!(r.page_count(), 3);
        assert!(r.is_page("/md/a"));
        assert!(!r.is_page("/x"));
        assert!(!r.is_page("/api/v1/health"));
        assert_eq!(r.redirect("/"), Some("/console"));
        assert!(from_route_tree("nothing", &[]).is_err());
    }

    const SAMPLE: &str = "# console routes\npage /\npage /agents\npage /md/$name # one segment\nredirect /home /agents\n";

    #[test]
    fn parse_and_match() {
        let r = Routes::parse(SAMPLE).unwrap();
        assert_eq!(r.page_count(), 3);
        assert!(r.is_page("/"));
        assert!(r.is_page("/agents"));
        assert!(!r.is_page("/agents/"));
        assert!(!r.is_page("/agents/x"));
        assert!(r.is_page("/md/readme"));
        assert!(!r.is_page("/md"));
        assert!(!r.is_page("/md/a/b"));
        assert!(!r.is_page("/nope"));
        assert_eq!(r.redirect("/home"), Some("/agents"));
        assert_eq!(r.redirect("/"), None);
    }

    #[test]
    fn rejects_bad_lines() {
        assert!(Routes::parse("page agents").is_err());
        assert!(Routes::parse("page /.env").is_err());
        assert!(Routes::parse("page /a/$").is_err());
        assert!(Routes::parse("redirect / https://evil.example/").is_err());
        assert!(Routes::parse("redirect / //evil.example").is_err());
        assert!(Routes::parse("serve /x").is_err());
        let e = Routes::parse("page /\nbogus").unwrap_err();
        assert_eq!(e.line, 2);
    }
}
