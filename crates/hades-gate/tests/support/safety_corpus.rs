//! S5.2 admin-safety corpus for `hades_gate::adapter::check_gaia` (slot 208).
//!
//! Every [`ATTACKS`] case is a full GAIA `Execute` request: a HADES system
//! name, a target and the exact plan steps. The tests mint a VALID admin token
//! for exactly that action, target and plan (the worst case: the admin was
//! tricked into signing it) and every case must still be refused. [`LEGIT`]
//! must still be approved with a token and dry-run without one. Plans are
//! data only: nothing in this file is ever executed.
//!
//! Shared by `tests/safety_corpus.rs`, `tests/real_safety_corpus.rs` and
//! `examples/safety_corpus_enum.rs` (prints the table in
//! docs/security/hades-safety-corpus.md).

// Shared by several targets; each uses a different subset.
#![allow(dead_code)]

/// Refusal categories (task row 208).
pub const CATEGORIES: &[&str] = &[
    "destructive",
    "secret",
    "account",
    "opaque",
    "protected",
    "never-unroute",
    "action",
];

/// One request.
pub struct Case {
    /// One of [`CATEGORIES`].
    pub cat: &'static str,
    /// Short description (shown in the doc table).
    pub desc: &'static str,
    /// GAIA HADES system name passed to `check_gaia`.
    pub system: &'static str,
    /// Target service.
    pub target: &'static str,
    /// Plan steps (joined with `\n` by `gaia_plan_bytes`).
    pub steps: &'static [&'static str],
}

const fn c(
    cat: &'static str,
    desc: &'static str,
    system: &'static str,
    target: &'static str,
    steps: &'static [&'static str],
) -> Case {
    Case {
        cat,
        desc,
        system,
        target,
        steps,
    }
}

/// Destructive plan on the benign target `galion-tuner`, heal-apply.
const fn d(desc: &'static str, steps: &'static [&'static str]) -> Case {
    c("destructive", desc, "heal-apply", "galion-tuner", steps)
}
const fn s(desc: &'static str, steps: &'static [&'static str]) -> Case {
    c("secret", desc, "heal-apply", "galion-tuner", steps)
}
const fn a(desc: &'static str, steps: &'static [&'static str]) -> Case {
    c("account", desc, "heal-apply", "galion-tuner", steps)
}
const fn o(desc: &'static str, steps: &'static [&'static str]) -> Case {
    c("opaque", desc, "heal-apply", "galion-tuner", steps)
}
/// Protected target with an otherwise ordinary plan.
const fn pt(desc: &'static str, target: &'static str) -> Case {
    c("protected", desc, "heal-apply", target, OK_PLAN)
}
/// Never-unroute target (VPS itself, DNS, mail, backup) with an ordinary plan.
const fn nt(desc: &'static str, target: &'static str) -> Case {
    c("never-unroute", desc, "heal-apply", target, OK_PLAN)
}
/// Never-unroute service named inside the plan of a benign target.
const fn np(desc: &'static str, steps: &'static [&'static str]) -> Case {
    c("never-unroute", desc, "heal-apply", "galion-one", steps)
}
/// A system name that can never be approved.
const fn act(desc: &'static str, system: &'static str) -> Case {
    c("action", desc, system, "galion-tuner", OK_PLAN)
}

