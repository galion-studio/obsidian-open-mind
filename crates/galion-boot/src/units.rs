//! B55: systemd unit renderer. One `.service` per [[service]] (plus a
//! `.timer` when `timer_every_s` is set). Staged files carry no [Install]
//! section; `--install-section` adds `WantedBy=multi-user.target`.

use crate::config::Service;

/// Quote one ExecStart word for systemd when needed.
pub fn quote(w: &str) -> String {
    if !w.is_empty()
        && w.chars()
            .all(|c| !c.is_whitespace() && !"\"'\\;$%".contains(c))
    {
        w.to_string()
    } else {
        let esc = w
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
            .replace('$', "$$");
        format!("\"{esc}\"")
    }
}

pub fn render_service(s: &Service, install: bool) -> String {
    let mut o = String::new();
    o.push_str(
        "# SPDX-License-Identifier: MIT\n# SPDX-FileCopyrightText: 2026 Slavik / Galion Studio\n",
    );
    o.push_str("# Generated by `galion-boot render-units`. STAGED: not installed, not enabled.\n");
    o.push_str("[Unit]\n");
    o.push_str(&format!("Description={}\n", s.description));
    let mut after = vec!["network-online.target".to_string()];
    after.extend(s.after.iter().cloned());
    o.push_str(&format!(
        "After={}\nWants=network-online.target\n",
        after.join(" ")
    ));
    if s.kind == "simple" {
        o.push_str("StartLimitIntervalSec=300\nStartLimitBurst=10\n");
    }
    o.push_str("\n[Service]\n");
    o.push_str(&format!("Type={}\n", s.kind));
    let exec: Vec<String> = s.argv.iter().map(|w| quote(w)).collect();
    o.push_str(&format!("ExecStart={}\n", exec.join(" ")));
    if let Some(w) = &s.workdir {
        o.push_str(&format!("WorkingDirectory={w}\n"));
    }
    if let Some(u) = &s.user {
        o.push_str(&format!("User={u}\n"));
    }
    for e in &s.env {
        o.push_str(&format!("Environment={}\n", quote(e)));
    }
    for f in &s.env_files {
        o.push_str(&format!("EnvironmentFile={f}\n"));
    }
    if s.kind == "simple" {
        o.push_str(&format!(
            "Restart={}\nRestartSec={}\n",
            s.restart, s.restart_sec
        ));
    }
    if let Some(n) = s.nice {
        o.push_str(&format!("Nice={n}\n"));
    }
    if let Some(m) = &s.memory_max {
        o.push_str(&format!("MemoryMax={m}\n"));
    }
    if s.harden {
        o.push_str("NoNewPrivileges=yes\nPrivateTmp=yes\nProtectSystem=strict\nProtectKernelTunables=yes\nProtectControlGroups=yes\nRestrictSUIDSGID=yes\nLockPersonality=yes\n");
        if !s.read_write.is_empty() {
            let rw: Vec<String> = s.read_write.iter().map(|p| format!("-{p}")).collect();
            o.push_str(&format!("ReadWritePaths={}\n", rw.join(" ")));
        }
    }
    if install && s.timer_every_s.is_none() {
        o.push_str("\n[Install]\nWantedBy=multi-user.target\n");
    }
    o
}

pub fn render_timer(s: &Service, every: u64, install: bool) -> String {
    let mut o = String::new();
    o.push_str(
        "# SPDX-License-Identifier: MIT\n# SPDX-FileCopyrightText: 2026 Slavik / Galion Studio\n",
    );
    o.push_str("# Generated by `galion-boot render-units`. STAGED: not installed, not enabled.\n");
    o.push_str(&format!(
        "[Unit]\nDescription={} (every {every} s)\n\n",
        s.description
    ));
    o.push_str(&format!(
        "[Timer]\nOnBootSec=30s\nOnUnitActiveSec={every}s\nAccuracySec=5s\nUnit={}.service\n",
        s.name
    ));
    if install {
        o.push_str("\n[Install]\nWantedBy=timers.target\n");
    }
    o
}

/// (file name, body) for every unit of every service.
pub fn render_all(services: &[Service], install: bool) -> Vec<(String, String)> {
    let mut v = Vec::new();
    for s in services {
        v.push((format!("{}.service", s.name), render_service(s, install)));
        if let Some(e) = s.timer_every_s {
            v.push((format!("{}.timer", s.name), render_timer(s, e, install)));
        }
    }
    v
}
