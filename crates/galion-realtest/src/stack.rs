//! Boots the whole stack on the box: writes fixture configs, renders one
//! `boot.toml`, and starts every long-running service under the stack's own
//! plain supervisor (`galion-boot supervise`), exactly the non-systemd boot
//! path. The supervisor runs in its own process group, so teardown is one
//! group signal. Children get a clean environment (no inherited keys).

use crate::http::{self, Stub};
use std::fs;
use std::io::Read;
use std::os::unix::fs::PermissionsExt;
use std::os::unix::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant};

/// Port offsets from the base port (default 19500, slot-14 full-stack range).
pub mod off {
    pub const ONE_STORE: u16 = 0;
    pub const ONE_STORE_MOUTH: u16 = 1;
    pub const ONE_NOSTORE: u16 = 2;
    pub const ONE_NOSTORE_MOUTH: u16 = 3;
    pub const ONE_EMPTY: u16 = 4;
    pub const ONE_EMPTY_MOUTH: u16 = 5;
    pub const MEMORY: u16 = 10;
    pub const TUNER: u16 = 20;
    pub const DESK: u16 = 30;
    pub const STUB: u16 = 40;
    pub const NERVE: u16 = 50;
    pub const NERVE_VOICE: u16 = 51;
    pub const MAX: u16 = 51;
}

/// Binaries the box stack needs. `openmind-nerve`/`galion-nerve` is optional.
pub const REQUIRED: &[&str] = &[
    "galion-boot",
    "galion-one",
    "openmind-memory",
    "tuner",
    "galion-desk",
    "link-watch",
    "guardian-tick",
    "persona-plex-relay",
];
pub const NERVE_BINS: &[&str] = &["openmind-nerve", "galion-nerve"];

#[derive(Debug, Clone)]
pub struct Bins {
    pub dir: PathBuf,
}

impl Bins {
    pub fn path(&self, name: &str) -> PathBuf {
        self.dir.join(name)
    }
    pub fn has(&self, name: &str) -> bool {
        self.path(name).is_file()
    }
    pub fn missing(&self) -> Vec<&'static str> {
        REQUIRED.iter().copied().filter(|b| !self.has(b)).collect()
    }
    pub fn nerve(&self) -> Option<PathBuf> {
        NERVE_BINS
            .iter()
            .map(|b| self.path(b))
            .find(|p| p.is_file())
    }
}

/// Run `cargo build --release` for the stack binaries (CPU-polite).
pub fn build(repo: &Path, jobs: u32) -> Result<String, String> {
    let mut args: Vec<String> = ["-n", "10", "cargo", "build", "--release", "--locked", "-j"]
        .iter()
        .map(|s| s.to_string())
        .collect();
    args.push(jobs.to_string());
    for b in REQUIRED {
        args.push("-p".into());
        args.push((*b).into());
    }
    let t = Instant::now();
    let out = Command::new("nice")
        .args(&args)
        .current_dir(repo)
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .output()
        .map_err(|e| format!("cargo: {e}"))?;
    let tail = tail_text(&String::from_utf8_lossy(&out.stderr), 15);
    if !out.status.success() {
        return Err(format!("cargo build failed:\n{tail}"));
    }
    Ok(format!(
        "nice {} ({} ms)",
        args.join(" "),
        t.elapsed().as_millis()
    ))
}

/// A relative `bin_dir` (CI passes `target/release`) is made absolute against
/// the current directory: galion-boot refuses a relative `argv[0]`.
pub fn locate(bin_dir: Option<&Path>, repo: &Path) -> Bins {
    if let Some(d) = bin_dir {
        return Bins {
            dir: std::path::absolute(d).unwrap_or_else(|_| d.to_path_buf()),
        };
    }
    let target = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| repo.join("target"));
    Bins {
        dir: target.join("release"),
    }
}

pub fn tail_text(text: &str, n: usize) -> String {
    let lines: Vec<&str> = text.lines().collect();
    lines[lines.len().saturating_sub(n)..].join("\n")
}

pub fn tail_file(path: &Path, n: usize) -> String {
    fs::read_to_string(path)
        .map(|t| tail_text(&t, n))
        .unwrap_or_default()
}

fn rand_hex(bytes: usize) -> String {
    let mut raw = vec![0u8; bytes];
    if let Ok(mut f) = fs::File::open("/dev/urandom") {
        let _ = f.read_exact(&mut raw);
    }
    raw.iter().map(|b| format!("{b:02x}")).collect()
}

fn toml_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// One supervised service.
#[derive(Debug, Clone)]
pub struct Svc {
    pub name: String,
    pub argv: Vec<String>,
    pub env: Vec<(String, String)>,
    pub env_files: Vec<PathBuf>,
    pub restart_sec: u64,
    /// (port, path) for readiness.
    pub health: Option<(u16, String)>,
}

pub fn render_boot(log_dir: &Path, sup_dir: &Path, svcs: &[Svc]) -> String {
    let mut t = format!(
        "# Generated by galion-realtest. Fixture only: no secrets, loopback only.\n[boot]\nlog_dir = {}\nsupervisor_dir = {}\n",
        toml_str(&log_dir.to_string_lossy()),
        toml_str(&sup_dir.to_string_lossy())
    );
    for s in svcs {
        let list = |v: Vec<String>| v.iter().map(|x| toml_str(x)).collect::<Vec<_>>().join(", ");
        t.push_str(&format!(
            "\n[[service]]\nname = {}\ndescription = {}\nargv = [{}]\nenv = [{}]\nenv_files = [{}]\nrestart = \"always\"\nrestart_sec = {}\n",
            toml_str(&s.name),
            toml_str(&format!("realtest {}", s.name)),
            list(s.argv.clone()),
            list(s.env.iter().map(|(k, v)| format!("{k}={v}")).collect()),
            list(s.env_files.iter().map(|p| p.to_string_lossy().into_owned()).collect()),
            s.restart_sec
        ));
        if let Some((port, path)) = &s.health {
            t.push_str(&format!(
                "[service.health]\nport = {port}\npath = {}\n",
                toml_str(path)
            ));
        }
    }
    t
}

pub struct Stack {
    pub base: u16,
    pub bins: Bins,
    pub fx: PathBuf,
    pub svcs: Vec<Svc>,
    pub stub: Stub,
    /// Random per-run fixture pairing code (not a secret: a throwaway store).
    pub pair_code: String,
    /// Random per-run fixture memory key (lives in an env file, never logged).
    pub mem_key: String,
    pub nerve: bool,
    sup: Option<Child>,
    pub boot_ms: u128,
    /// Readiness time per service (ms since supervisor start), None = never.
    pub ready: Vec<(String, Option<u128>)>,
}

impl Stack {
    pub fn addr(&self, offset: u16) -> String {
        format!("127.0.0.1:{}", self.base + offset)
    }
    pub fn path(&self, rel: &str) -> PathBuf {
        self.fx.join(rel)
    }
    pub fn log_tail(&self, name: &str, n: usize) -> String {
        tail_file(&self.fx.join("logs").join(format!("{name}.log")), n)
    }
    pub fn pid(&self, name: &str) -> Option<u32> {
        fs::read_to_string(self.fx.join("sup/pids").join(name))
            .ok()
            .and_then(|s| s.trim().parse().ok())
    }

    /// Write fixtures and start the stub plus the supervisor.
    pub fn up(bins: Bins, out: &Path, base: u16, with_nerve: bool) -> Result<Stack, String> {
        let fx = out.join("fixture");
        if fx.file_name().is_some_and(|n| n == "fixture") && fx.exists() {
            fs::remove_dir_all(&fx).map_err(|e| format!("clean {}: {e}", fx.display()))?;
        }
        for d in [
            "logs",
            "sup",
            "home",
            "hermes",
            "galion-home/one",
            "one-store",
            "one-nostore",
            "one-empty",
            "memory",
            "tuner-www",
            "state",
            "one-dir",
            "relay",
            "guardian",
            "nerve",
        ] {
            fs::create_dir_all(fx.join(d)).map_err(|e| format!("mkdir {d}: {e}"))?;
        }
        let w = |rel: &str, body: &str| {
            fs::write(fx.join(rel), body).map_err(|e| format!("write {rel}: {e}"))
        };
        let pair_code = format!("RT{}", rand_hex(4).to_ascii_uppercase());
        let code_hash = crate::sha256::hex(pair_code.as_bytes());
        let store = format!(
            "{{\"codeHash\":\"{code_hash}\",\"tokenHash\":\"\",\"tokenHashes\":[],\"deviceHash\":\"\",\"fails\":0,\"lockedUntil\":0}}\n"
        );
        w("one-store/admin-device.json", &store)?;
        w("one-empty/admin-device.json", "{}\n")?;
        w(
            "galion-home/one/index.html",
            "<!doctype html><html><body><p>realtest fixture</p></body></html>\n",
        )?;
        w(
            "tuner-www/index.html",
            "<!doctype html><html><body>tuner fixture</body></html>\n",
        )?;
        w("tuner-www/app.js", "console.log('fixture');\n")?;
        w("tuner-www/pitch.js", "export const a4 = 440;\n")?;
        w("tuner-www/style.css", "body{margin:0}\n")?;
        let mem_key = rand_hex(16);
        w(
            "memory.env",
            &format!("OPENMIND_MEMORY_API_KEY={mem_key}\n"),
        )?;
        let _ = fs::set_permissions(fx.join("memory.env"), fs::Permissions::from_mode(0o600));

        let stub_addr = format!("127.0.0.1:{}", base + off::STUB);
        let stub = Stub::start(&stub_addr)?;
        let p = |rel: &str| fx.join(rel).to_string_lossy().into_owned();
        let bin = |n: &str| bins.path(n).to_string_lossy().into_owned();
        let kv = |pairs: &[(&str, String)]| -> Vec<(String, String)> {
            pairs
                .iter()
                .map(|(k, v)| (k.to_string(), v.clone()))
                .collect()
        };
        let a = |o: u16| format!("127.0.0.1:{}", base + o);
        let absent = p("absent/none");
        let one = |name: &str, port: u16, mouth: u16, store: String| Svc {
            name: name.into(),
            argv: vec![bin("galion-one")],
            env: kv(&[
                ("ONE_BIND", a(port)),
                ("ONE_MOUTH_BIND", a(mouth)),
                ("ONE_DEVICE_STORE", store),
                ("ONE_HERMES_DIR", p("hermes")),
                ("ONE_HERMES_ENV", absent.clone()),
                ("ONE_NO_WARM", "1".into()),
                ("ONE_WARM_MIND", "0".into()),
                ("GALION_HOME", p("galion-home")),
                ("GALION_EAR", stub_addr.clone()),
                ("GALION_MOUTH", stub_addr.clone()),
                ("GALION_MIND", stub_addr.clone()),
                ("GALION_EYE", stub_addr.clone()),
                ("OPENROUTER_API_KEY", String::new()),
                ("OPENROUTER_KEY_FILE", absent.clone()),
                ("OPENROUTER_BASE_URL", format!("http://{stub_addr}")),
            ]),
            env_files: vec![],
            restart_sec: 2,
            health: Some((base + port, "/health".into())),
        };
        let mut svcs = vec![
            one(
                "one-store",
                off::ONE_STORE,
                off::ONE_STORE_MOUTH,
                p("one-store/admin-device.json"),
            ),
            one(
                "one-nostore",
                off::ONE_NOSTORE,
                off::ONE_NOSTORE_MOUTH,
                p("one-nostore/admin-device.json"),
            ),
            one(
                "one-empty",
                off::ONE_EMPTY,
                off::ONE_EMPTY_MOUTH,
                p("one-empty/admin-device.json"),
            ),
            Svc {
                name: "openmind-memory".into(),
                argv: vec![bin("openmind-memory")],
                env: kv(&[
                    ("OPENMIND_MEMORY_HOST", "127.0.0.1".into()),
                    ("OPENMIND_MEMORY_PORT", (base + off::MEMORY).to_string()),
                    ("OPENMIND_MEMORY_DATA_DIR", p("memory")),
                    ("OPENMIND_MEMORY_INSTANCE_ID", "realtest".into()),
                ]),
                env_files: vec![fx.join("memory.env")],
                restart_sec: 2,
                health: Some((base + off::MEMORY, "/health".into())),
            },
            Svc {
                name: "tuner".into(),
                argv: vec![bin("tuner")],
                env: kv(&[
                    ("TUNER_ADDR", a(off::TUNER)),
                    ("TUNER_ROOT", p("tuner-www")),
                ]),
                env_files: vec![],
                // Long enough that guardian-tick sees the kill before the heal.
                restart_sec: 3,
                health: Some((base + off::TUNER, "/health".into())),
            },
            Svc {
                name: "galion-desk".into(),
                argv: vec![bin("galion-desk")],
                env: kv(&[
                    ("DESK_BIND", a(off::DESK)),
                    ("DESK_OLLAMA", stub_addr.clone()),
                    ("DESK_STATE_DIR", p("state")),
                    ("DESK_ONE_DIR", p("one-dir")),
                    ("DESK_HERMES_DIR", p("hermes")),
                    ("DESK_HERMES_BIN", "/bin/false".into()),
                    ("OPENMIND_CONFIG", absent.clone()),
                ]),
                env_files: vec![],
                restart_sec: 2,
                health: Some((base + off::DESK, "/health".into())),
            },
            Svc {
                name: "link-watch".into(),
                argv: vec![bin("link-watch")],
                env: kv(&[
                    ("LINK_WATCH_OUT", p("state/link.json")),
                    ("LINK_WATCH_LAPTOP", p("state/laptop.json")),
                    ("LINK_WATCH_LOG", p("state/link-log.json")),
                    ("LINK_WATCH_OLLAMA_URL", format!("http://{stub_addr}")),
                    ("LINK_WATCH_HERMES_URL", format!("http://{stub_addr}")),
                    ("OPENMIND_CONFIG", absent.clone()),
                ]),
                env_files: vec![],
                restart_sec: 2,
                health: None,
            },
        ];
        let nerve = match (with_nerve, bins.nerve()) {
            (true, Some(nb)) => {
                svcs.push(Svc {
                    name: "nerve".into(),
                    argv: vec![nb.to_string_lossy().into_owned()],
                    env: kv(&[
                        ("NERVE_ADDR", a(off::NERVE)),
                        ("NERVE_DATA_DIR", p("nerve")),
                        ("NERVE_GAIA_BIN", "/bin/false".into()),
                        ("NERVE_DEPLOY_BIN", "/bin/false".into()),
                        ("NERVE_DEPLOY_BACKUPS", p("nerve/backups")),
                        ("NERVE_SWITCH_DIR", p("nerve/switch")),
                        ("NERVE_TELEGRAM_ENV", absent.clone()),
                        ("NERVE_VOICE_UNIT", "realtest-none.service".into()),
                        ("NERVE_VOICE_PORT", (base + off::NERVE_VOICE).to_string()),
                        ("NERVE_DISK_PATH", p("")),
                    ]),
                    env_files: vec![],
                    restart_sec: 2,
                    health: Some((base + off::NERVE, "/healthz".into())),
                });
                true
            }
            _ => false,
        };
        // Every service also gets a private HOME and the Zagreb TZ.
        for s in &mut svcs {
            s.env.push(("HOME".into(), p("home")));
            s.env.push(("TZ".into(), "Europe/Zagreb".into()));
        }
        let boot = render_boot(&fx.join("logs"), &fx.join("sup"), &svcs);
        w("boot.toml", &boot)?;

        let log = fs::File::create(fx.join("logs/supervisor.log")).map_err(|e| e.to_string())?;
        let err = log.try_clone().map_err(|e| e.to_string())?;
        let t0 = Instant::now();
        let sup = Command::new(bins.path("galion-boot"))
            .args(["supervise", "--config"])
            .arg(fx.join("boot.toml"))
            .env_clear()
            .env(
                "PATH",
                std::env::var("PATH").unwrap_or_else(|_| "/usr/bin:/bin".into()),
            )
            .env("TZ", "Europe/Zagreb")
            .env("HOME", fx.join("home"))
            .stdin(Stdio::null())
            .stdout(log)
            .stderr(err)
            .process_group(0)
            .spawn()
            .map_err(|e| format!("start galion-boot supervise: {e}"))?;
        let mut st = Stack {
            base,
            bins,
            fx,
            svcs,
            stub,
            pair_code,
            mem_key,
            nerve,
            sup: Some(sup),
            boot_ms: 0,
            ready: Vec::new(),
        };
        st.wait_ready(t0, Duration::from_secs(30));
        st.boot_ms = t0.elapsed().as_millis();
        Ok(st)
    }

    fn wait_ready(&mut self, t0: Instant, limit: Duration) {
        let mut pending: Vec<(String, String, String)> = self
            .svcs
            .iter()
            .filter_map(|s| {
                s.health
                    .as_ref()
                    .map(|(port, path)| (s.name.clone(), format!("127.0.0.1:{port}"), path.clone()))
            })
            .collect();
        while !pending.is_empty() && t0.elapsed() < limit {
            pending.retain(|(name, addr, path)| {
                let ok = http::request(addr, "GET", path, &[], b"", Duration::from_millis(800))
                    .is_ok_and(|r| r.status == 200);
                if ok {
                    self.ready
                        .push((name.clone(), Some(t0.elapsed().as_millis())));
                }
                !ok
            });
            std::thread::sleep(Duration::from_millis(150));
        }
        for (name, _, _) in pending {
            self.ready.push((name, None));
        }
    }

    /// True while the supervisor process is alive.
    pub fn supervisor_alive(&mut self) -> bool {
        self.sup
            .as_mut()
            .is_some_and(|c| matches!(c.try_wait(), Ok(None)))
    }

    /// Signal the whole process group, wait, then verify every port is free.
    pub fn down(&mut self) -> Result<String, String> {
        let mut notes = Vec::new();
        if let Some(mut c) = self.sup.take() {
            let pgid = c.id().to_string();
            let _ = signal_group("TERM", &pgid);
            let t = Instant::now();
            while t.elapsed() < Duration::from_secs(3) && matches!(c.try_wait(), Ok(None)) {
                std::thread::sleep(Duration::from_millis(100));
            }
            // The supervisor has no signal handler, so TERM ends it at once;
            // a KILL sweep catches any child that ignored TERM.
            std::thread::sleep(Duration::from_millis(300));
            let _ = signal_group("KILL", &pgid);
            let _ = c.wait();
            notes.push(format!(
                "process group {pgid} signalled (TERM, then KILL sweep)"
            ));
        }
        self.stub.stop();
        let open: Vec<String> = (0..=off::MAX)
            .map(|o| self.addr(o))
            .filter(|a| http::port_open(a))
            .collect();
        if open.is_empty() {
            notes.push(format!(
                "ports {}-{} all free",
                self.base,
                self.base + off::MAX
            ));
            Ok(notes.join("; "))
        } else {
            Err(format!(
                "still listening after teardown: {}",
                open.join(", ")
            ))
        }
    }
}

impl Drop for Stack {
    fn drop(&mut self) {
        if self.sup.is_some() {
            let _ = self.down();
        }
    }
}

/// `kill -SIG -- -PGID` through the shell builtin (no libc dependency).
pub fn signal_group(sig: &str, pgid: &str) -> bool {
    Command::new("sh")
        .args([
            "-c",
            "kill -s \"$1\" -- \"-$2\" 2>/dev/null",
            "sh",
            sig,
            pgid,
        ])
        .status()
        .is_ok_and(|s| s.success())
}

/// `kill -SIG PID` for one of our own children.
pub fn signal_pid(sig: &str, pid: u32) -> bool {
    Command::new("sh")
        .args([
            "-c",
            "kill -s \"$1\" \"$2\" 2>/dev/null",
            "sh",
            sig,
            &pid.to_string(),
        ])
        .status()
        .is_ok_and(|s| s.success())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn boot_toml_escapes_and_has_health() {
        let s = Svc {
            name: "x".into(),
            argv: vec!["/bin/a\"b".into()],
            env: vec![("K".into(), "v w".into())],
            env_files: vec![],
            restart_sec: 1,
            health: Some((19141, "/health".into())),
        };
        let t = render_boot(Path::new("/l"), Path::new("/s"), &[s]);
        assert!(t.contains("argv = [\"/bin/a\\\"b\"]"));
        assert!(t.contains("env = [\"K=v w\"]"));
        assert!(t.contains("[service.health]\nport = 19141"));
    }

    #[test]
    fn port_layout_fits_the_full_stack_range() {
        const { assert!(19500 + off::MAX <= 19599) };
    }

    #[test]
    fn relative_bin_dir_becomes_absolute() {
        // CI runs `--bin-dir target/release`; galion-boot needs absolute argv[0].
        let b = locate(Some(Path::new("target/release")), Path::new("/r"));
        assert!(b.dir.is_absolute(), "{}", b.dir.display());
        assert!(b.dir.ends_with("target/release"));
        assert!(b.path("galion-one").is_absolute());
        let a = locate(Some(Path::new("/x/release")), Path::new("/r"));
        assert_eq!(a.dir, PathBuf::from("/x/release"));
    }
}
