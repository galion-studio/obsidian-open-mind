//! Stylesheet for `/admin/plans` and `/admin/accounts`.
//!
//! The base sheet in `css.rs` is at its 20 KiB budget, so these rules are a
//! second file, linked only on the admin screens. They use the palette
//! already defined there (`--c-*`, `--sans`, `--display`, `--mono`, `--r-*`)
//! and do not add tokens. The sheet has no `:root` block.

use crate::css;
use crate::Reply;
use std::sync::OnceLock;

/// Rules for the plan and account screens. No custom properties.
const RULES: &str = r#"
.adm h1{font-family:var(--display),var(--sans)}
.adm-hold{margin-top:1.25rem;border:1px solid var(--c-line);border-radius:var(--r-lg);background:var(--c-surface);padding:1rem 1.25rem}
.adm-hold p{font-family:var(--sans);color:var(--c-muted);font-size:.9375rem;line-height:1.5}
.adm-k{font-family:var(--mono);font-size:11px;letter-spacing:.14em;text-transform:uppercase;color:var(--c-subtle)}
.adm-price{font-family:var(--mono);font-variant-numeric:tabular-nums;color:var(--c-fg);font-size:.95rem}
.adm .adm-on{color:var(--c-ok)}
.adm .adm-off{color:var(--c-muted)}
"#;

struct Cached {
    body: String,
    href: String,
    etag: String,
}

fn cached() -> &'static Cached {
    static S: OnceLock<Cached> = OnceLock::new();
    S.get_or_init(|| {
        let mut body = String::from(
            "/* Galion console UI (admin plans). Generated by crates/console-ui/src/admin_sheet.rs. */\n",
        );
        for line in RULES.lines().filter(|l| !l.trim().is_empty()) {
            body.push_str(line.trim());
            body.push('\n');
        }
        let h = css::fnv64(body.as_bytes());
        Cached {
            href: format!("/_ui/admin.{h:016x}.css"),
            etag: format!("\"{h:016x}\""),
            body,
        }
    })
}

/// Content-hashed path. Stable for the life of the process.
pub fn href() -> &'static str {
    &cached().href
}

pub fn is_sheet(path: &str) -> bool {
    path == href()
}

pub fn reply() -> Reply {
    let s = cached();
    Reply {
        status: 200,
        headers: vec![
            ("Content-Type".into(), "text/css; charset=utf-8".into()),
            (
                "Cache-Control".into(),
                "public, max-age=31536000, immutable".into(),
            ),
            ("ETag".into(), s.etag.clone()),
        ],
        body: s.body.as_bytes().to_vec(),
    }
}

/// Class names this sheet defines (for the coverage test).
pub fn classes() -> Vec<String> {
    let mut out = Vec::new();
    let b = RULES.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'.' && i + 1 < b.len() && b[i + 1].is_ascii_alphabetic() {
            let s = i + 1;
            let mut e = s;
            while e < b.len() && (b[e].is_ascii_alphanumeric() || b[e] == b'-' || b[e] == b'_') {
                e += 1;
            }
            out.push(RULES[s..e].to_string());
            i = e;
        } else {
            i += 1;
        }
    }
    out.sort();
    out.dedup();
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sheet_reuses_palette_variables_and_adds_none() {
        let s = &cached().body;
        assert!(
            s.len() <= 2 * 1024,
            "admin sheet {} B exceeds 2 KiB",
            s.len()
        );
        assert!(s.contains("var(--display)"));
        assert!(s.contains("var(--sans)"));
        assert!(s.contains("var(--mono)"));
        assert!(s.contains("var(--c-fg)"));
        assert!(s.contains("var(--c-muted)"));
        assert!(s.contains("var(--c-line)"));
        assert!(s.contains("var(--c-surface)"));
        assert!(s.contains("var(--c-ok)"));
        assert!(s.contains("var(--c-subtle)"));
        assert!(s.contains("var(--r-lg)"));
        assert!(!s.contains(":root"), "admin sheet must not define tokens");
        // A SPDX tag inside this comment is read by comply as the file licence.
        assert!(!s.contains("SPDX-License-Identifier"));
        assert!(!s.contains("--display:"));
        assert!(!s.contains("--sans:"));
        assert!(!s.contains("--mono:"));
        assert!(!s.contains("--c-bg:"));
        assert!(!s.contains("@import"));
        assert_eq!(s.matches('{').count(), s.matches('}').count());
        assert!(
            !css::sheet().contains(".adm-hold"),
            "admin rules must stay off the base sheet"
        );
        assert!(classes().contains(&"adm-price".to_string()));
        assert!(href().starts_with("/_ui/admin."));
        assert!(is_sheet(href()));
    }
}
