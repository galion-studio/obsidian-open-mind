//! Build the offline RustSec snapshot the `rustsec` cortex sensor (T2.4)
//! embeds: `crates/openmind-nerve/data/rustsec/advisories.tsv`.
//!
//! ```text
//! git clone --depth 1 https://github.com/rustsec/advisory-db /path/advisory-db
//! cargo run -p openmind-nerve --example rustsec_snapshot -- /path/advisory-db \
//!     > crates/openmind-nerve/data/rustsec/advisories.tsv
//! ```
//!
//! Only the TOML front matter of `crates/*/RUSTSEC-*.md` is read; no prose is
//! copied. Kept per advisory: id, package, kind, CVSS v3 base score
//! (computed here from the vector; v4 vectors get `-`), patched and
//! unaffected version requirements, and aliases (ids only). Skipped:
//! withdrawn advisories and advisories marked `license = "CC-BY-4.0"`
//! (imported GHSA text: CC-BY is not on the swarm's licence allowlist, so
//! including them is an owner decision). The rest of the database is CC0-1.0.
//! The header records the database commit; pass it as the second argument
//! (`git -C /path/advisory-db log -1 --format='%H %cI'`).

use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let mut args = std::env::args().skip(1);
    let db = args
        .next()
        .expect("usage: rustsec_snapshot <advisory-db dir> [commit info]");
    let commit = args.collect::<Vec<_>>().join(" ");
    let mut rows = vec![];
    let (mut skipped_cc_by, mut skipped_withdrawn) = (0, 0);
    let crates = Path::new(&db).join("crates");
    let mut dirs: Vec<_> = std::fs::read_dir(&crates)
        .expect("crates dir")
        .flatten()
        .map(|e| e.path())
        .collect();
    dirs.sort();
    for d in dirs {
        let mut files: Vec<_> = std::fs::read_dir(&d)
            .into_iter()
            .flatten()
            .flatten()
            .map(|e| e.path())
            .collect();
        files.sort();
        for f in files
            .into_iter()
            .filter(|f| f.extension().is_some_and(|x| x == "md"))
        {
            let text = std::fs::read_to_string(&f).expect("read advisory");
            let front = text
                .split_once("```toml")
                .and_then(|(_, r)| r.split_once("```"))
                .map(|(t, _)| t)
                .unwrap_or_else(|| panic!("{}: no toml front matter", f.display()));
            let v: toml::Value =
                toml::from_str(front).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
            let a = &v["advisory"];
            if a.get("withdrawn").is_some() {
                skipped_withdrawn += 1;
                continue;
            }
            if a.get("license").and_then(|l| l.as_str()) == Some("CC-BY-4.0") {
                skipped_cc_by += 1;
                continue;
            }
            let s = |k: &str| a.get(k).and_then(|x| x.as_str()).unwrap_or("").to_string();
            let list = |t: Option<&toml::Value>| -> String {
                let v: Vec<String> = t
                    .and_then(|x| x.as_array())
                    .into_iter()
                    .flatten()
                    .filter_map(|x| x.as_str().map(|s| s.trim().to_string()))
                    .collect();
                if v.is_empty() {
                    "-".into()
                } else {
                    v.join(";")
                }
            };
            let kind = match s("informational").trim() {
                "" => "vuln".to_string(),
                k => k.to_string(),
            };
            let cvss = cvss3_score(&s("cvss"))
                .map(|x| format!("{x:.1}"))
                .unwrap_or("-".into());
            let versions = v.get("versions");
            rows.push(format!(
                "{}\t{}\t{}\t{}\t{}\t{}\t{}",
                s("id"),
                s("package"),
                kind,
                cvss,
                list(versions.and_then(|x| x.get("patched"))),
                list(versions.and_then(|x| x.get("unaffected"))),
                list(a.get("aliases")),
            ));
        }
    }
    rows.sort();
    let mut out = String::new();
    let _ = writeln!(out, "# SPDX-License-Identifier: CC0-1.0");
    let _ = writeln!(
        out,
        "# RustSec advisory-db snapshot (https://github.com/rustsec/advisory-db), CC0-1.0 data."
    );
    let _ = writeln!(out, "# commit: {commit}");
    let _ = writeln!(out, "# generated by crates/openmind-nerve/examples/rustsec_snapshot.rs; {} advisories; skipped: {skipped_withdrawn} withdrawn, {skipped_cc_by} CC-BY-4.0 (GHSA import)", rows.len());
    let _ = writeln!(
        out,
        "# id\tpackage\tkind\tcvss3\tpatched\tunaffected\taliases"
    );
    for r in rows {
        out.push_str(&r);
        out.push('\n');
    }
    print!("{out}");
}

/// CVSS v3.0/v3.1 base score (FIRST spec section 7.1, Roundup per 3.1
/// appendix A). None for other versions or malformed vectors.
fn cvss3_score(vector: &str) -> Option<f64> {
    let rest = vector
        .strip_prefix("CVSS:3.1/")
        .or_else(|| vector.strip_prefix("CVSS:3.0/"))?;
    let mut m = std::collections::HashMap::new();
    for part in rest.split('/') {
        let (k, v) = part.split_once(':')?;
        m.insert(k, v);
    }
    let changed = *m.get("S")? == "C";
    let av = match *m.get("AV")? {
        "N" => 0.85,
        "A" => 0.62,
        "L" => 0.55,
        "P" => 0.2,
        _ => return None,
    };
    let ac = match *m.get("AC")? {
        "L" => 0.77,
        "H" => 0.44,
        _ => return None,
    };
    let pr = match (*m.get("PR")?, changed) {
        ("N", _) => 0.85,
        ("L", false) => 0.62,
        ("L", true) => 0.68,
        ("H", false) => 0.27,
        ("H", true) => 0.5,
        _ => return None,
    };
    let ui = match *m.get("UI")? {
        "N" => 0.85,
        "R" => 0.62,
        _ => return None,
    };
    let cia = |k: &str| -> Option<f64> {
        Some(match *m.get(k)? {
            "H" => 0.56,
            "L" => 0.22,
            "N" => 0.0,
            _ => return None,
        })
    };
    let iss = 1.0 - (1.0 - cia("C")?) * (1.0 - cia("I")?) * (1.0 - cia("A")?);
    let impact = if changed {
        7.52 * (iss - 0.029) - 3.25 * (iss - 0.02f64).powi(15)
    } else {
        6.42 * iss
    };
    let expl = 8.22 * av * ac * pr * ui;
    if impact <= 0.0 {
        return Some(0.0);
    }
    let raw = if changed {
        (1.08 * (impact + expl)).min(10.0)
    } else {
        (impact + expl).min(10.0)
    };
    let i = (raw * 100_000.0).round() as i64;
    Some(if i % 10_000 == 0 {
        i as f64 / 100_000.0
    } else {
        ((i / 10_000) + 1) as f64 / 10.0
    })
}

#[cfg(test)]
mod tests {
    #[test]
    fn cvss3_known_scores() {
        // smallvec RUSTSEC-2021-0003 (NVD 9.8), a scope-changed 10.0 and a 5.3.
        assert_eq!(
            super::cvss3_score("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H"),
            Some(9.8)
        );
        assert_eq!(
            super::cvss3_score("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:C/C:H/I:H/A:H"),
            Some(10.0)
        );
        assert_eq!(
            super::cvss3_score("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:N/I:N/A:L"),
            Some(5.3)
        );
        assert_eq!(
            super::cvss3_score("CVSS:3.1/AV:L/AC:L/PR:L/UI:N/S:U/C:H/I:H/A:H"),
            Some(7.8)
        );
        assert_eq!(super::cvss3_score("CVSS:4.0/AV:N"), None);
    }
}
